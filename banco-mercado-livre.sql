CREATE TABLE endereco(
id_endereco INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
cep VARCHAR(12),
rua VARCHAR(254),
numero INTEGER,
complemento INTEGER,
nome VARCHAR (254),
telefone VARCHAR (15)
)


SELECT e.ID_ENDERECO, e.CEP, e.RUA, e.NUMERO, e.COMPLEMENTO, e.NOME, e.TELEFONE 
FROM ENDERECO e 

DELETE FROM ENDERECO e
WHERE e.ID_ENDERECO  = 1

DELETE FROM ENDERECO e
WHERE e.ID_ENDERECO  = 2

CREATE TABLE pagamento(
id_pagamento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
numero_cartao VARCHAR(20),
nome VARCHAR (254),
vencimento DATE,
codigo VARCHAR(3),
cpf VARCHAR(15)
)

SELECT p.ID_PAGAMENTO, p.NUMERO_CARTAO, p.NOME, p.VENCIMENTO, p.CODIGO, p.CPF 
FROM PAGAMENTO p 
